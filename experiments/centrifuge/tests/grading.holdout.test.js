/**
 * 서술형 첨삭 — 바깥에서 던지는 문장.
 *
 * `tests/grading.test.js` 는 첨삭을 만든 쪽이 쓴 테스트다. 만든 사람이 자기 키워드 목록에
 * 맞춰 문장을 지으면 테스트가 공허해진다 — 목록이 자기 자신을 검사할 뿐이다.
 * 이 파일의 문장은 **구현을 보지 않고** 지어서 던진 것이다.
 *
 * 바나나랩에서 실제로 겪은 일이다. 처음 던졌을 때 9개 중 6개가 어긋났고, 6개 전부
 * **맞게 쓴 답을 미달로 판정한 것**이었다. 반대 방향(엉성한 답이 통과) 오류는 0건이었다.
 * 그때 `npm run check` 는 99개 전부 초록불이었다 — 만든 쪽 테스트도, 구현이 이미 본
 * 문장도 이걸 잡지 못했다.
 *
 * 그래서 이 파일이 있다. 여기 있는 문장은 **키워드 목록에서 역산해서 만들지 말 것.**
 * 판정이 어긋났다고 여기 문장을 고치는 것도 금지다 — 그러면 이 테스트의 존재 이유가
 * 사라진다. 어긋난 문장은 그대로 두고, 고칠 곳은 구현이다.
 * 새 문장을 더할 때는 `src/ui/grading.js` 를 열지 말고 먼저 지어라.
 *
 * 이 기능에서 가장 나쁜 결과는 테스트가 빨간불이 되는 것이 아니라
 * **맞는 말을 쓴 학생에게 미달이라고 말하는 것**이다. 그래서 통과해야 할 문장이 더 많다.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { gradeQuestion, QUESTIONS, STATUS } from '../src/ui/grading.js';

/* ---------------- 2번 문항 — 갈라진 층의 차례와 정체 ---------------- */

test('2번 문항: 층을 차례로 짚은 답은 낱말을 어떻게 골랐든 통과한다', () => {
  // 같은 것을 보고도 학생마다 부르는 이름이 다르다. 「적혈구층」이라고 쓴 답도,
  // 「진한 붉은 부분」이라고만 쓴 답도, 「가라앉은 것」이라고 쓴 답도 다 맞게 본 것이다.
  const answers = [
    '바깥쪽부터 적혈구층, 연층, 혈장 순서로 갈라졌다. 적혈구층은 산소를 나르는 적혈구가 눌려 쌓인 것이고, 연층은 백혈구와 혈소판이 모인 아주 얇은 띠이고, 혈장은 남은 액체 성분이다.',
    '회전 바깥쪽 끝에 진한 붉은 부분이 제일 두껍게 있었고, 그 다음에 눈에 겨우 보이는 흐린 흰 띠가 있었고, 축 쪽에는 맑은 노란 액체가 있었다. 붉은 것은 산소를 옮기는 세포가 모인 것, 흰 띠는 몸을 지키는 세포와 피를 굳히는 조각들, 노란 액체는 나머지 액체 부분이다.',
    '제일 바깥으로 가라앉은 것이 가장 두껍고 색이 어두웠는데 이게 적혈구가 다져진 부분이다. 그 안쪽에 잘 보이지도 않는 가느다란 회색 줄이 하나 있었고 백혈구랑 혈소판이라고 배웠다. 맨 안쪽 연한 노란 부분은 액체라서 혈장이다.',
    '무거운 것일수록 바깥으로 밀려나기 때문에 적혈구가 제일 먼저 바깥에 쌓이고, 그 위에 백혈구와 혈소판이 얇게 얹히고, 마지막에 남은 액체가 축 쪽에 떠 있다.',
    '① 암적색 적혈구층 ② 회백색 연층 ③ 담황색 혈장. 적혈구층은 산소를 운반하는 세포, 연층은 면역을 맡는 세포와 혈소판, 혈장은 물과 단백질이 녹아 있는 액체다.',
    '바깥쪽부터 붉은 세포 덩어리, 얇은 흰 줄, 누런 물 순서였다. 붉은 덩어리는 적혈구, 흰 줄은 백혈구와 혈소판, 누런 물은 혈장이다.',
    '자를 대 보니 회전 바깥쪽 끝에서부터 짙은 빨강이 절반 가까이 차지했고 그 다음이 아주 가는 흐린 띠, 나머지가 옅은 노랑이었다. 빨간 부분은 적혈구가 압축된 것, 가는 띠는 백혈구와 혈소판이 모인 곳, 옅은 노랑은 혈장이다.',
  ];
  for (const text of answers) {
    const { status } = gradeQuestion('q2', text);
    assert.equal(status, STATUS.PASS, `맞게 쓴 답을 미달로 판정했습니다: "${text}"`);
  }
});

test('2번 문항: 한쪽 층만 말하면 통과하지 못한다', () => {
  const answers = [
    '바깥쪽에 적혈구층이 있었다.',
    '적혈구층이 바깥쪽 끝에 아주 두껍게 생겼다. 색이 어둡고 진했다.',
    '혈장이 축 쪽에 떠 있었다. 연한 노란색이었다.',
  ];
  for (const text of answers) {
    const { status } = gradeQuestion('q2', text);
    assert.notEqual(status, STATUS.PASS, `한쪽 층만 말했는데 통과했습니다: "${text}"`);
  }
});

test('2번 문항: 갈라졌다고만 하고 무엇인지 말하지 않으면 통과하지 못한다', () => {
  for (const text of ['층이 세 개로 갈라졌다.', '색이 서로 다른 부분으로 나뉘었다.']) {
    assert.notEqual(gradeQuestion('q2', text).status, STATUS.PASS, `"${text}"`);
  }
});

/* ---------------- 질문 ⓐ — 반대쪽에 빈 모세관을 넣는 까닭 ---------------- */

test('질문 ⓐ: 균형이 왜 필요한지 짚은 답은 낱말을 어떻게 골랐든 통과한다', () => {
  // 「흔들린다」를 학생들은 여러 말로 쓴다 — 덜덜거린다, 비틀거린다, 요동친다, 출렁인다.
  const answers = [
    '한쪽만 무거우면 돌 때 회전판이 덜덜거려서 층이 깨끗하게 안 갈린다. 양쪽 무게를 같게 하려고 빈 것을 넣는다.',
    '무게 중심이 한가운데에 오게 하려고 넣는다. 안 그러면 회전판이 한쪽으로 쏠려 비틀거리고 층의 경계가 흐려진다.',
    '균형을 맞추려고 넣는 것이다. 반대쪽이 비어 있으면 돌리는 동안 요동쳐서 속도도 잘 안 붙고 결과도 뿌옇게 섞인다.',
    '자전거 바퀴에 한쪽만 뭐가 붙어 있으면 흔들리는 것처럼, 모세관도 한쪽에만 있으면 회전판이 출렁여서 제대로 돌아가지 않는다. 그래서 같은 무게를 반대쪽에 둔다.',
  ];
  for (const text of answers) {
    const { status } = gradeQuestion('qa', text);
    assert.equal(status, STATUS.PASS, `맞게 쓴 답을 미달로 판정했습니다: "${text}"`);
  }
});

test('질문 ⓐ: 절차만 적으면 통과하지 못한다', () => {
  const answers = [
    '반대쪽 빨대에 빈 모세관을 하나 넣었다.',
    '선생님이 넣으라고 하셔서 넣었다.',
    '두 개를 마주 보게 꽂고 끈을 당겼다.',
  ];
  for (const text of answers) {
    assert.notEqual(gradeQuestion('qa', text).status, STATUS.PASS, `"${text}"`);
  }
});

/* ---------------- 잘 쓴 한 문장을 짧다고 되돌려 보내지 않는다 ---------------- */

test('마침표를 하나만 찍어도 내용이 있으면 통과한다', () => {
  // 마침표를 어떻게 찍는지는 학생마다 다르고 우리가 볼 것이 아니다.
  const q2 = '바깥쪽부터 적혈구층과 연층과 혈장 순인데 적혈구층은 산소를 나르는 적혈구가 다져진 것이고 연층은 백혈구와 혈소판이 모인 얇은 띠이고 혈장은 남은 액체 성분이다.';
  assert.equal(gradeQuestion('q2', q2).status, STATUS.PASS, `"${q2}"`);

  const qa = '반대쪽이 비어 있으면 무게가 한쪽으로 쏠려서 회전판이 흔들리고 그러면 층이 흐리게 섞이기 때문에 빈 모세관을 넣어 균형을 맞춘다';
  assert.equal(gradeQuestion('qa', qa).status, STATUS.PASS, `"${qa}"`);
});

/* ---------------- 3번 문항 — 아직 할 수 없는 일 ---------------- */

test('3번 문항은 공유 보드가 없으면 미달이 아니라 아직 할 수 없음이다', () => {
  // '미달' 로 보이면 학생에게 "내가 못 한 일" 로 읽힌다. 다른 모둠 결과를 볼 길이 아직 없다.
  const answers = [
    '',
    '다른 모둠 것을 봤다.',
    '옆 모둠은 붉은 층이 우리보다 짧았다. 우리가 덜 돌린 것 같다.',
  ];
  for (const text of answers) {
    assert.equal(gradeQuestion('q3', text).status, STATUS.UNAVAILABLE, `"${text}"`);
  }
});

/* ---------------- 아이에게 보여 줄 문장 ---------------- */

test('되돌려 주는 말이 학생을 나무라지 않는다', () => {
  for (const q of QUESTIONS) {
    assert.ok(q.feedback && q.feedback.trim(), `${q.id} 에 되돌려 주는 말이 없습니다`);
    assert.equal(/틀렸|잘못|오답|실패|미달/.test(q.feedback), false,
      `${q.id} 의 문구가 학생을 나무랍니다: "${q.feedback}"`);
    if (q.hint) {
      assert.equal(/틀렸|잘못|오답|실패|미달/.test(q.hint), false,
        `${q.id} 의 권유 문구가 학생을 나무랍니다: "${q.hint}"`);
    }
  }
});

test('미달 판정에 붙는 말도 학생을 나무라지 않는다', () => {
  // 실제로 학생 눈에 닿는 것은 QUESTIONS 의 문구가 아니라 gradeQuestion 이 돌려주는 말이다.
  const shallow = [
    ['q2', '층이 세 개로 갈라졌다.'],
    ['qa', '반대쪽 빨대에 빈 모세관을 하나 넣었다.'],
  ];
  for (const [id, text] of shallow) {
    const { message } = gradeQuestion(id, text);
    if (!message) continue;
    assert.equal(/틀렸|잘못|오답|실패|미달/.test(message), false,
      `${id} 의 되돌림 문구가 학생을 나무랍니다: "${message}"`);
  }
});
