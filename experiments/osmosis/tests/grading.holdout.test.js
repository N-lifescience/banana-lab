test('질문 ⓐ: 절차만 적으면 통과하지 못한다', () => {
  for (const text of ['거름종이를 댔다.', '선생님이 대라고 하셨다.']) {
    assert.notEqual(gradeQuestion('qa', text).status, STATUS.PASS, `"${text}"`);
  }
});

