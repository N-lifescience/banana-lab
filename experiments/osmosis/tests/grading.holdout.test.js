/**
 * 규칙을 안 본 쪽이 「통과해야 마땅하다」고 쓴 문장은 **한 줄도 떨어지면 안 된다.**
 * 이 기능에서 가장 나쁜 결과는 테스트가 빨간불이 되는 것이 아니라
 * **맞는 말을 쓴 학생에게 미달이라고 말하는 것**이다.
 */
for (const [id, sets] of Object.entries(HOLDOUT)) {
  test(`바깥 문장 [${id}] — 통과해야 마땅한 답이 한 줄도 떨어지지 않는다`, () => {
    const fell = sets.pass.filter((s) => gradeQuestion(id, s).status !== STATUS.PASS);
    assert.deepEqual(fell, [], `맞게 쓴 답을 미달로 판정했습니다:\n  ${fell.join('\n  ')}`);
  });
}

/**
 * 「더 써야 마땅한 답」 이 통과하는 것은 **값이 싼 잘못**이다 (`docs/06`).
 * 아무 점수도 매기지 않고 진행도 막지 않으므로, 헐겁게 통과하면 아무 일도 안 일어난다.
 * 그래서 개수만 못 박아 둔다 — **늘어나면 목록이 헐거워진 것**이니 그때 들여다본다.
 *
 * 지금 통과하는 둘:
 *   qa 「설탕물을 갈아주려고 그렇게 했습니다」 — 짧지만 까닭을 말하기는 한다
 *   q3 「식물세포가 동물세포보다 더 튼튼해서」 — 벽을 짚지 않았지만 방향은 맞다.
 *      여기를 조이면 「겉에 딱딱한 껍질 같은 게 있어서」 가 함께 떨어진다
 */
test('바깥 문장 — 헐겁게 통과하는 답이 늘지 않았다', () => {
  const loose = [];
  for (const [id, sets] of Object.entries(HOLDOUT)) {
    for (const s of sets.more) {
      if (gradeQuestion(id, s).status === STATUS.PASS) loose.push(`[${id}] ${s}`);
    }
  }
  assert.equal(loose.length, 2,
    `헐겁게 통과하는 답이 ${loose.length}개입니다 (2개였습니다):\n  ${loose.join('\n  ')}`);
});
