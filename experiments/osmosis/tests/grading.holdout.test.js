/* ---------------- 아이에게 보여 줄 문장 ---------------- */

test('되돌려 주는 말이 학생을 나무라지 않는다', () => {
  for (const q of QUESTIONS) {
    assert.ok(q.feedback && q.feedback.trim(), `${q.id} 에 되돌려 주는 말이 없습니다`);
    assert.equal(/틀렸|잘못|오답|실패|미달/.test(q.feedback), false,
      `${q.id} 의 문구가 학생을 나무랍니다: "${q.feedback}"`);
    if (q.hint) {
      assert.equal(/틀렸|잘못|오답|실패|미달/.test(q.hint), false,
        `${q.id} 의 권유 문구가 학생을 나무랍니다: "${q.hint}"`);
    }
  }
});

test('되돌려 주는 말이 답을 알려 주지 않는다', () => {
  // 「10~15 % 사이입니다」 라고 적어 두면 첨삭이 곧 정답 공개가 된다.
  for (const q of QUESTIONS) {
    for (const line of [q.feedback, q.hint].filter(Boolean)) {
      assert.equal(/\d\s*%/.test(line), false, `${q.id} 의 문구가 농도를 흘립니다: "${line}"`);
    }
  }
});

test('견주는 말이 없어도 막지 않고 권유만 한다', () => {
  // 세포벽을 짚었으면 통과다. 깊이는 판정이 아니라 권유로 다룬다.
  const shallow = '세포벽이 있기 때문이다. 그래서 모양이 그대로였다.';
  const r = gradeQuestion('q3', shallow);
  assert.equal(r.status, STATUS.PASS, '세포벽을 짚었으면 통과여야 합니다');
  assert.ok(r.message, '견주는 말이 없으면 권유 문구가 붙어야 합니다');
});

