/**
 * 증류수(저장액) + 설탕 용액 5 · 10 · 15 · 20 %.
 *
 * 이 4단 농도열이 이 실험을 정량 탐구로 만든다 — 「어느 농도에서 세포 절반이
 * 원형질분리를 일으키는가」로 세포액 농도를 추정한다. 농도를 하나만 두면 그 탐구가 사라진다.
 *
 * **소금물 10 % 3종 세트를 쓰지 않는 이유와 0.9 % 를 등장액이라 부르지 않는 이유는
 * `AGENTS.md` §2.5 에 적혀 있다.** 여기서 농도를 바꾸기 전에 그것부터 읽을 것.
 */
export const SOLUTIONS = ['WATER', 'S05', 'S10', 'S15', 'S20'];

/** 설탕 질량백분율 (w/v %). 증류수는 0 이다. */
export const SOLUTION_PCT = { WATER: 0, S05: 5, S10: 10, S15: 15, S20: 20 };

export const isSolution = (id) => Object.prototype.hasOwnProperty.call(SOLUTION_PCT, id);
export const pctOf = (id) => SOLUTION_PCT[id] ?? 0;

/* ------------------------------------------------------------------ */
/* 세포액 농도 — 이 파일에서 가장 조심해야 하는 값                      */
/* ------------------------------------------------------------------ */

/**
 * 세포액의 삼투 농도. **설탕 질량백분율로 환산한 값**이다.
 *
 * ── [확인 필요] — 다만 **학생이 구할 값**이지 화면이 말해 줄 값이 아니다 ──────
 * **이 두 값은 1차 출처를 대지 못했다.** 찾아본 것과 그 결과를 그대로 적어 둔다.
 *
 * 확실한 것:
 *   · 설탕(수크로스) 분자량 342.3 g/mol → 10 % (w/v) = 0.29 M, 15 % = 0.44 M, 20 % = 0.58 M
 *   · 서울대 과학교육연구소 생물 실험 연수 교재가 **설탕 5 · 10 · 15 · 20 %** 네 농도를 주고
 *     「어느 농도에서 **약 반수의 세포가** 원형질분리를 일으켰는가」로 세포액 농도를
 *     **학생이 추정하게** 한다는 것 (허브 세션이 웨이브 2 전에 확인)
 *
 * 못 박지 못한 것:
 *   · 양파 표피의 한계원형질분리를 **NaCl 약 0.2 M(≈1.2 %)** 로 보고한 자료가 있으나
 *     전문 접근에 실패했다 (허브 세션 확인)
 *   · 영어권 실습 자료는 수크로스 **0.3~0.8 M** 농도열을 쓰고, 한 데이터셋은
 *     0.2 M 에서 4 % · 1.0 M 에서 100 % 라 **50 % 지점이 0.5 M(≈17 % w/v) 언저리**다.
 *     여기 잡은 12 % 보다 높다. 다만 적양파·흰양파, 담근 시간, 온도에 따라 갈리고
 *     그 자료도 1차 출처가 아니다.
 *
 * 설계상 지켜야 하는 것은 하나뿐이다 — **50 % 지점이 5~20 % 창 **안쪽**에 있고
 * 첫 칸·끝 칸이 아닐 것.** 12 % 는 10 % 와 15 % 사이에 놓여 그 조건을 만족한다.
 * 17 % 로 잡으면 15 % 와 20 % 사이가 된다. 둘 다 탐구가 성립한다.
 *
 * **그래서 이 숫자는 절대 화면에 나오지 않는다.** 그 숫자를 학생이 관찰로 추정하는 것이
 * 이 실험의 탐구이고, 화면이 먼저 말하면 탐구가 사라진다
 * (micrometer 실험이 `trueUmPerDiv` 를 같은 이유로 화면에 안 낸다).
 * `tests/rules.test.js` 가 UI 문자열에 이 값이 새어 나오지 않는지 검사한다.
 *
 * **교실에서 재어 본 값이 있으면 여기만 고친다.** 나머지는 전부 파생값이고,
 * `tests/rules.test.js` 의 「50 % 지점이 10~15 % 사이」 도 함께 고치면 된다.
 */
export const CELL_SAP_PCT = 12;

/**
 * 세포마다 세포액 농도가 다른 폭 (± %).
 *
 * **이 폭이 0 이면 이 실험이 성립하지 않는다.** 모든 세포가 같은 농도에서 한꺼번에
 * 원형질분리를 일으켜 버리면 「절반이 원형질분리를 일으키는 농도」라는 판정이 사라진다.
 * 실제로도 같은 시야 안에서 정도가 갈린다 (`AGENTS.md` §2.5).
 *
 * [확인 필요] 폭 자체의 출처도 없다. 위 CELL_SAP_PCT 와 함께 다시 볼 것.
 */
export const CELL_SAP_SPREAD_PCT = 5;

/**
 * 세포 하나의 세포액 농도. 좌표의 순수 함수다 (그리는 순서에 매이지 않는다).
 *
 * 두 해시를 더해 삼각분포를 만든다 — 균등분포를 쓰면 농도-비율 곡선이 직선이 되어
 * 「가운데 농도에서 절반」이 우연처럼 보인다. 가운데가 두툼한 편이 실제에 가깝다.
 *
 * @param {(...ints:number[]) => number} h  0~1 을 내는 위치 해시 (assets/geometry.js 의 hash 를 부분 적용)
 */
export function sapPct(h, ...where) {
  const t = h(101, ...where) + h(102, ...where) - 1;   // -1 ~ +1, 가운데가 두툼하다
  return CELL_SAP_PCT + t * CELL_SAP_SPREAD_PCT;
}

/* ------------------------------------------------------------------ */
/* 원형질체                                                            */
/* ------------------------------------------------------------------ */

/**
 * 원형질체의 부피비. **1 이면 세포벽을 꽉 채운 상태**다.
 *
 *   바깥 농도 ≤ 세포액 농도  →  1
 *     물이 들어오려 하지만 **세포벽이 버틴다.** 팽압이 올라갈 뿐 부피는 거의 안 는다.
 *     그래서 저장액에서도 **터지지 않는다** — 적혈구의 용혈과 갈리는 지점이다.
 *   바깥 농도 > 세포액 농도  →  세포액 농도 / 바깥 농도
 *     원형질체가 세포벽에서 떨어져 나온다. 세포벽에 눌리지 않으므로
 *     반트호프 관계(농도 × 부피 = 일정)가 그대로 성립한다.
 *
 * **세포벽은 줄지 않는다.** 줄어드는 것은 원형질체뿐이다 — 시야 렌더러가 이것을
 * 그림으로 지켜야 한다 (`tasks/T03-fov-and-harness.md`).
 */
export function protoplastRatio(externalPct, cellSapPct) {
  if (!(cellSapPct > 0)) return 1;
  if (externalPct <= cellSapPct) return 1;
  return cellSapPct / externalPct;
}

/**
 * 원형질체가 줄어드는 **방향별 비율.** 부피비 하나를 긴 변·짧은 변 배율로 나눈다.
 *
 * 등방으로(모든 방향 같은 비율로) 줄인다고 두면 틀린 그림이 나온다. 원형질체는 벽에서
 * 떨어지면서 **둥글게 뭉치기 때문에 긴 변 쪽 끝에서 훨씬 많이 물러난다.** 실제 시야에서
 * 원형질분리가 「양쪽 끝이 오므라든」 모습으로 보이는 것이 그래서다.
 *
 * 두 지수를 더하면 1 이라 넓이비는 그대로 부피비를 따른다 (0.75 + 0.25).
 */
export function protoplastAxes(ratio) {
  const r = Math.max(0, Math.min(1, ratio));
  return { long: Math.pow(r, 0.75), short: Math.pow(r, 0.25) };
}

/**
 * 눈으로 틈이 보이기 시작하는 부피비.
 *
 * 한계원형질분리는 **바깥 농도 = 세포액 농도** 인 딱 그 점이지만, 그 점에서는 틈이 0 이라
 * 현미경으로 세어지지 않는다. 세는 사람이 「떨어졌다」고 판정하는 지점은 조금 뒤다.
 */
export const PLASMOLYSIS_RATIO = 0.95;

export const isPlasmolysed = (ratio) => ratio < PLASMOLYSIS_RATIO;

/**
 * 이 농도에서 원형질분리를 일으키는 세포의 비율 (0~1).
 *
 * **화면에 숫자로 내보내지 않는다.** 이 값을 시야에서 읽어 내는 것이 학생의 일이다.
 * 여기 있는 것은 모형이 뜻대로 도는지 테스트가 확인하기 위한 것이다.
 *
 * 시야 렌더러는 격자 좌표 `(i, j)` 로 세포를 만들고 여기서는 1차원 번호 `k` 로 만든다.
 * **분포는 같지만 세포 하나하나가 같지는 않다** — 화면에 세어질 개수와 이 값이
 * 소수점까지 맞을 필요는 없다. 맞아야 한다고 착각해서 두 곳을 억지로 묶지 말 것.
 */
export function plasmolysedFraction(externalPct, h, n = 400) {
  let count = 0;
  for (let k = 0; k < n; k++) {
    if (isPlasmolysed(protoplastRatio(externalPct, sapPct(h, k)))) count++;
  }
  return count / n;
}

