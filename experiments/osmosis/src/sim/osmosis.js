/**
 * 세포가 지금 **평형을 이루고 있는 바깥 농도.**
 *
 * 상태에는 이 스칼라 하나만 둔다. 세포마다의 부피비는 여기서 파생된다.
 * 이렇게 해 두면 학생이 평형에 닿기 전에 용액을 또 바꿔도 자연스럽게 이어진다 —
 * 「직전 평형」을 따로 기억할 필요가 없다.
 */
export const OSMOSIS_K = 0.12;

/** 이 차이 아래로 좁혀지면 평형으로 본다. 지수 접근은 영원히 닿지 않기 때문이다. */
export const SETTLED_PCT = 0.15;

/**
 * 한 틱만큼 평형 농도를 목표로 옮긴다.
 * @param {number} equivPct  지금 평형을 이루고 있는 농도
 * @param {number} targetPct 덮개 유리 아래 용액의 실효 농도
 */
export function stepEquivPct(equivPct, targetPct, seconds = 1, speed = 10) {
  const next = targetPct + (equivPct - targetPct) * Math.exp(-OSMOSIS_K * seconds * speed);
  return Math.abs(next - targetPct) < SETTLED_PCT ? targetPct : next;
}

export const isSettled = (equivPct, targetPct) => Math.abs(equivPct - targetPct) < SETTLED_PCT;

