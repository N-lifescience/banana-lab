/* 눈에 보이는 단계 — 화면이 「무엇이 보였는지」 를 말할 때만 쓴다        */
/* ------------------------------------------------------------------ */

/**
 * 이 농도에서 시야가 어느 단계로 보이는가.
 *
 * 세포마다 세포액 농도가 `CELL_SAP_PCT ± CELL_SAP_SPREAD_PCT` 로 흩어져 있으므로,
 * 그 아래에서는 한 세포도 갈라지지 않고 그 위에서는 전부 갈라진다. 사이가 **섞인 구간**이고,
 * 「어느 농도에서 절반이 원형질분리를 일으키는가」 라는 물음이 성립하는 곳이 바로 거기다.
 *
 * **이 함수는 비율(숫자)을 돌려주지 않는다.** 세는 것은 학생의 일이다
 * (`docs/04-interaction-rules.md` 「화면이 답을 먼저 말하지 않는다」).
 *
 * @returns {'turgid'|'mixed'|'plasmolysed'}
 */
export function changeStage(equivPct) {
  if (equivPct <= CELL_SAP_PCT - CELL_SAP_SPREAD_PCT) return 'turgid';
  if (equivPct >= CELL_SAP_PCT + CELL_SAP_SPREAD_PCT) return 'plasmolysed';
  return 'mixed';
}
