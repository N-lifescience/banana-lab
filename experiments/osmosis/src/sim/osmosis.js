/* 용액 치환 — 거름종이가 하는 일                                       */
/* ------------------------------------------------------------------ */

/**
 * 거름종이를 **한 번** 댔을 때 치환되는 정도.
 *
 * 두 번이면 다 바뀐다. 한 번만 대고 관찰하면 **섞인 농도**가 되어 변화가 어중간하다 —
 * 그것을 막지 않고 그대로 보여 주는 것이 이 프로젝트의 방식이다 (`AGENTS.md` §2.1).
 */
export const EXCHANGE_PER_WICK = 0.5;

/**
 * 지금 덮개 유리 아래에 실제로 있는 용액의 농도.
 * 치환이 덜 됐으면 **원래 용액과 새 용액이 섞인 농도**다.
 *
 * 농도를 용액 이름이 아니라 **숫자로** 받는 이유: 씻지 않은 스포이트로 옮기면
 * 실제로 나가는 농도가 병에 붙은 이름표와 다르다. 이름으로만 다루면 그 어긋남을
 * 담을 데가 없어, 오염을 「보여 주기만 하고 결과에는 없는 것」으로 만들게 된다.
 */
export function effectivePct(fromPct, toPct, exchange = 0) {
  if (toPct === null || toPct === undefined) return fromPct ?? 0;
  const a = fromPct ?? 0;
  return a + (toPct - a) * Math.max(0, Math.min(1, exchange));
}

