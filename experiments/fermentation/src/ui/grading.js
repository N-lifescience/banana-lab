/**
 * 서술형 자동 첨삭.
 *
 * DOM 을 모르는 순수 모듈이다. 정답 일치가 아니라 **「근거로 쓸 만한 낱말이 들어 있는가」**만
 * 본다. 형태소 분석기 없이 단순 포함 검사로 충분하다 — 학생 문장을 정확히 판정하는 것이
 * 목적이 아니라 **다시 보게 만드는 것**이 목적이다.
 *
 * ── 비용은 비대칭이다 ──────────────────────────────────────────────
 * 이 첨삭은 점수를 매기지도, 진행을 막지도 않는다. 그러면
 *
 *   · 엉성한 답이 통과하는 비용   → 거의 0. 아무 일도 일어나지 않는다
 *   · 맞게 쓴 답이 미달로 뜨는 비용 → 크다. **아이가 자기가 틀렸다고 믿는다**
 *
 * 그래서 판정을 「어떤 낱말을 썼나」가 아니라 **「무엇에 대해 쓰고 있나」**로 둔다.
 * 무엇을 가리키는 말(효모·포도당·이산화 탄소)은 형용사보다 훨씬 닫힌 집합이라 목록으로 잡을 수 있다.
 * 깊이를 재는 낱말은 판정에서 **힌트로 강등**했다 — 통과시키되 더 써 보라고 권한다.
 *
 * ── 용어 없이 관찰만 쓴 답을 미달로 만들지 않는다 ──────────────────
 * 「효모를 안 넣으니 아무것도 안 나왔다」는 관찰을 정확히 쓴 것이고, 그 자체로 답이다.
 * 그래서 개념 계열과 관찰 계열을 `anyOf` 로 묶어 **둘 중 하나만 걸려도** 통과시킨다.
 *
 * 문항을 if 사슬로 짜지 않고 표(`QUESTIONS`) 하나로 내보낸다 — 테스트가 이 표를 통째로 훑어
 * 「되돌려 주는 말이 비었는지」 같은 것을 전 문항에 대해 검증할 수 있다.
 */

