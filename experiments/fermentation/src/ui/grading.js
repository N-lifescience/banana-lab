/**
 * 얼마나 썼는지는 **글자 수**로 잰다. 문장 수로 세지 않는다.
 *
 * 문장 수를 세면 잘 쓴 한 문장이 짧다고 되돌려 보내진다:
 *   「30 ℃ 에서 기체가 가장 많이 났고 55 ℃ 에서는 아예 안 났다」
 * 두 가지를 다 말했는데 마침표가 하나라 미달이 된다. 마침표를 어떻게 쓰는지는
 * 학생마다 다르고, 그건 우리가 볼 것이 아니다.
 */
function bodyLength(text) {
  return text.replace(/\s+/g, '').length;
}

/**
 * 글자 수 하한의 기본값.
 *
 * 20 자로 두었더니 **「온도가 높으면 기체가 훨씬 많이 났다」(16자)가 미달**이 됐다.
 * 다 말한 답인데 한국어가 짧아서 떨어진 것이다. 이 조건의 목적은 「났다」 같은
 * 한두 낱말짜리 답만 거르는 것뿐이라, 거기에 필요한 만큼만 둔다.
 */
const MIN_CHARS = 12;

const hasAny = (text, words) => words.some((w) => text.includes(w));

/**
 * 통과시킬지 정한다.
 *
 * 통과 조건은 **무엇에 대해 썼는가**와 **얼마나 썼는가** 둘뿐이다.
 * 깊이를 재는 낱말은 통과를 가르지 않고, 없으면 권유(`hint`)만 붙인다.
 *
 * @returns {{status: 'pass'|'more'|'unavailable', message: string|null}}
 */
export function grade(question, text) {
  if (question.available === false) {
    return { status: STATUS.UNAVAILABLE, message: question.feedback };
  }
  const t = (text ?? '').trim();
  // **빈칸에는 아무 말도 하지 않는다.** 쓰기도 전에 부족하다는 말부터 들으면 안 쓴다.
  if (!t) return { status: STATUS.MORE, message: null };

  const lengthOk = bodyLength(t) >= (question.minChars ?? MIN_CHARS);
  const subjectsOk = (question.subjects ?? []).every((words) => hasAny(t, words));
  const anyOfOk = !question.anyOf || question.anyOf.some((words) => hasAny(t, words));

  if (!lengthOk || !subjectsOk || !anyOfOk) {
    return { status: STATUS.MORE, message: question.feedback };
  }
  const deepOk = !question.depth || question.depth.some((words) => hasAny(t, words));
  return { status: STATUS.PASS, message: deepOk ? null : (question.hint ?? null) };
}

export function gradeQuestion(id, text) {
  const question = QUESTIONS.find((q) => q.id === id);
  if (!question) throw new Error(`알 수 없는 문항: ${id}`);
  return grade(question, text);
}

/** `scripts/check-grading.mjs` 가 쓰는 이름. */
export function gradeAnswer(id, text) {
  return gradeQuestion(id, text);
}
