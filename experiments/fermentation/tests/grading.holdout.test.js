/**
 * 채점기를 쓴 세션이 지은 답안. **값이 덜하다** — 자기 목록을 다시 확인하는 것에 가깝다.
 * 그래도 두는 것은, 목록을 좁히는 변경이 들어올 때 두 벌이 함께 잡기 때문이다.
 */
const SELF_GOOD = [
  ['qa', '효모가 포도당을 분해해서 이산화 탄소를 만들었고 그것이 맹관부에 모였다'],
  ['qa', '산소를 막아 두었더니 효모가 알코올 발효를 해서 기체가 나왔다'],
  ['q2', '30 ℃ 에서 기체가 가장 많이 났고 55 ℃ 에서는 거의 안 났다'],
  ['q2', '포도당이 진할수록 모인 기체가 많아졌다'],
  ['q3', '효모액과 같은 부피를 넣어 총 부피를 맞췄다. 그 관에서는 기체가 안 모였다'],
  ['q4', '수산화 칼륨을 넣으니 맹관부의 기체가 줄어들었다'],
  ['q5', '나머지를 같게 해야 무엇 때문에 달라졌는지 말할 수 있다'],
];

const failing = (rows) => rows
  .filter(([id, text]) => gradeQuestion(id, text).status !== STATUS.PASS)
  .map(([id, text]) => `[${id}] ${text.slice(0, 44)}…`);

test('바깥에서 지은 답안이 미달로 떨어지지 않는다', () => {
  const failed = failing(OUTSIDE_GOOD);
  assert.deepEqual(failed, [],
    `맞게 쓴 답이 미달로 떨어집니다 — **문장이 아니라 낱말 목록을 고치세요**`);
});

test('채점기를 쓴 쪽이 지은 답안도 통과한다', () => {
  assert.deepEqual(failing(SELF_GOOD), []);
});

/**
 * 한두 낱말짜리 답은 되돌려 보낸다.
 *
 * **이것은 느슨해도 된다.** 몇 개가 통과해도 아무 일도 안 일어난다.
 * 그래서 「전부 걸러야 한다」가 아니라 **「대부분은 걸러진다」**로 둔다 —
 * 여기를 빡빡하게 죄면 위 검사가 깨지고, 그쪽이 훨씬 비싸다.
 */
test('한두 낱말짜리 답은 대부분 되돌려 보낸다', () => {
  const caught = OUTSIDE_THIN.filter(([id, text]) => gradeQuestion(id, text).status !== STATUS.PASS);
  assert.ok(caught.length >= OUTSIDE_THIN.length - 2,
    `${OUTSIDE_THIN.length}개 중 ${caught.length}개만 걸러집니다`);
});

test('빈칸에는 아무 말도 하지 않는다', () => {
  // 쓰기도 전에 부족하다는 말부터 들으면 안 쓴다.
  for (const [id] of OUTSIDE_GOOD) {
    assert.equal(gradeQuestion(id, '').message, null, `${id} 가 빈칸에 첨삭을 띄웁니다`);
    assert.equal(gradeQuestion(id, '   ').message, null);
  }
});

test('「틀렸다」는 판정이 없다', () => {
  for (const [id, text] of [...OUTSIDE_GOOD, ...OUTSIDE_THIN]) {
    const r = gradeQuestion(id, text);
    assert.ok([STATUS.PASS, STATUS.MORE, STATUS.UNAVAILABLE].includes(r.status));
    if (r.message) assert.equal(/틀렸|잘못|오답/.test(r.message), false, r.message);
  }
});

test('문항 표의 되돌려 주는 말에 「틀렸」·「잘못」이 없다', async () => {
  const { QUESTIONS } = await import('../src/ui/grading.js');
  for (const q of QUESTIONS) {
    assert.ok(q.feedback && q.feedback.trim().length > 0, `${q.id} 의 feedback 이 비어 있습니다`);
    assert.equal(/틀렸|잘못/.test(q.feedback), false, `${q.id} 의 feedback: ${q.feedback}`);
    if (q.hint) assert.equal(/틀렸|잘못/.test(q.hint), false, `${q.id} 의 hint: ${q.hint}`);
  }
});
