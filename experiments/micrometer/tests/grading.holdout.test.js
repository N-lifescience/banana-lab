/* ---------------- 첨삭 문구 자체 ---------------- */

test('되돌려 주는 말이 이 실험에 없는 것을 말하지 않는다', () => {
  // 여기 있던 문항은 통째로 바나나랩 것이었다 — 대조군 (가)(나)(다) 를 견주라 하고
  // 첨삭이 「(가)에서는 무엇이 보였는지…」 라고 답했다. 이 실험에는 그 중 아무것도 없다.
  const banana = /\(가\)|\(나\)|\(다\)|대조군|아이오딘|녹말|전분|지방|지질|수단|청람|선홍/;
  for (const q of QUESTIONS) {
    for (const [what, line] of [['feedback', q.feedback], ['hint', q.hint]]) {
      if (!line) continue;
      assert.equal(banana.test(line), false,
        `${q.id} 의 ${what} 에 이 실험에 없는 말이 있습니다: ${line}`);
    }
  }
});

test('되돌려 주는 말은 나무라지 않는다', () => {
  for (const q of QUESTIONS) {
    assert.equal(/틀렸|잘못|안 됩니다|못했/.test(q.feedback), false,
      `${q.id} 의 feedback 이 나무랍니다: ${q.feedback}`);
  }
});
