/**
 * **이 파일에서 가장 중요한 검사다.**
 *
 * 바깥에서 온 답안만 따로 센다. 함께 세면 자기가 지은 문장이 수를 채워 주므로
 * 바깥 문장이 몇 개 떨어졌는지가 묻힌다.
 */
test('바깥에서 온 답안을 「더 쓰세요」로 되돌려 보내지 않는다', () => {
  const wrong = OUTSIDE_GOOD.filter(([id, text]) => gradeQuestion(id, text).status !== STATUS.PASS);
  assert.deepEqual(wrong.map(([id, t]) => `[${id}] ${t}`), [],
    `바깥에서 온 답안 ${wrong.length}/${OUTSIDE_GOOD.length} 개가 미달로 판정됐습니다`);
});

test('맞게 쓴 답을 「더 쓰세요」로 되돌려 보내지 않는다', () => {
  const wrong = [];
  for (const [id, text] of GOOD) {
    const r = gradeQuestion(id, text);
    if (r.status !== STATUS.PASS) wrong.push(`[${id}] ${text}`);
  }
  assert.deepEqual(wrong, [],
    `맞게 쓴 답 ${wrong.length}/${GOOD.length} 개가 미달로 판정됐습니다:\n  ${wrong.join('\n  ')}`);
});

test('통과한 답에 붙는 말이 나무라는 말이 아니다', () => {
  for (const [id, text] of GOOD) {
    const r = gradeQuestion(id, text);
    if (!r.message) continue;
    // 통과했는데 붙는 말은 **권유**여야 한다. 「틀렸다」·「부족하다」는 말이 있으면 안 된다.
    assert.ok(!/틀|부족|잘못|다시 쓰/.test(r.message),
      `[${id}] 통과했는데 나무라는 말이 붙습니다: ${r.message}`);
  }
});

test('한두 낱말짜리 답은 더 써 보라고 한다', () => {
  for (const [id, text] of THIN) {
    assert.equal(gradeQuestion(id, text).status, STATUS.MORE, `[${id}] "${text}" 가 통과했습니다`);
  }
});

