/**
 * 받침 조사. 마지막 글자에 받침이 있으면 `withJong`, 없으면 `noJong`.
 *
 * 「밀봉이(가) 다릅니다」처럼 괄호를 치면 학생이 읽다가 걸린다. 조건 이름이
 * `UI.controls` 에서 오므로 문장을 쓸 때는 무엇이 올지 알 수 없어, 여기서 고른다.
 * 한글이 아니면 받침 있는 쪽으로 둔다 — 「BTB 가」보다 「BTB 이」가 덜 어색한 경우가 없어서다.
 */
export function josa(word, withJong, noJong) {
  const c = String(word).charCodeAt(String(word).length - 1);
  if (c < 0xac00 || c > 0xd7a3) return noJong;
  return (c - 0xac00) % 28 ? withJong : noJong;
}

