/**
 * 서술형 첨삭 — 바깥에서 던지는 문장.
 *
 * `tests/grading.test.js` 는 첨삭을 만든 쪽이 쓴 테스트다. 만든 사람이 자기 키워드 목록에
 * 맞춰 문장을 지으면 테스트가 공허해진다 — 목록이 자기 자신을 검사할 뿐이다.
 *
 * 바나나랩에서 실제로 겪은 일: 처음 던졌을 때 9개 중 6개가 어긋났고, 6개 전부
 * **맞게 쓴 답을 미달로 판정한 것**이었다. 반대 방향(엉성한 답이 통과) 오류는 0건이었다.
 * 그때 `npm run check` 는 99개 전부 초록불이었다.
 *
 * ── 이 파일의 한계를 밝혀 둔다 ──────────────────────────────────────
 * 이 실험에서는 첨삭을 만든 세션이 이 문장들도 함께 지었다. **그건 바나나랩만큼 강한
 * 증거가 아니다.** 다만 문장을 **키워드 목록에서 역산하지 않고** 실제 절차와 현상에서
 * 먼저 지었고, 어긋난 것이 나와도 **목록을 넓혀 맞추지 않았다.**
 * 다음에 이 저장소를 여는 사람은 `docs/banana-tasks/T02-PROMPT.md` 형식으로
 * **채점 로직을 안 본 세션**에게 학생 답안을 새로 쓰게 해서 여기에 더하라.
 *
 * 여기 있는 문장은 **키워드 목록에서 역산해서 만들지 말 것.**
 * 목록을 넓히려고 여기 문장을 고치는 것도 금지다 — 그러면 이 테스트의 존재 이유가 사라진다.
 *
 * 이 기능에서 가장 나쁜 결과는 테스트가 빨간불이 되는 것이 아니라
 * **맞는 말을 쓴 학생에게 미달이라고 말하는 것**이다. 그래서 통과해야 할 문장이 더 많다.
 */

