test('2번: 순서를 말하지 않은 답에는 더 써 보라고 한다', () => {
  // 이 문항이 묻는 것은 "어떤 순서였는가" 다. 색만 늘어놓은 답에는 그것이 없다.
  const r = gradeQuestion('q2', '색이 여러 가지로 나뉘어서 신기했다. 주황색이랑 노란색이랑 초록색이 보였다.');
  assert.equal(r.status, STATUS.MORE);
  assert.ok(r.message && r.message.trim().length > 0, '무엇을 더 쓰라는지 말해 줘야 합니다');
});

/* ---------------- 판정의 성질 ---------------- */

test('어느 문항도 "틀렸다" 고 말하지 않는다', () => {
  const harsh = /틀렸|잘못|오답|아닙니다|아니에요|다시 하세요/;
  const texts = ['', '몰라요', '색소가 갈라진다', '주황이 위에 있었다'];
  for (const q of QUESTIONS) {
    for (const text of texts) {
      const r = gradeQuestion(q.id, text);
      assert.notEqual(r.status, 'fail', '이 첨삭에는 "틀림" 판정이 없습니다');
      if (r.message) {
        assert.equal(harsh.test(r.message), false, `${q.id} 가 나무랍니다: "${r.message}"`);
      }
    }
  }
});

test('빈칸에도 판정은 나오지만, 화면은 그것을 띄우지 않는다', () => {
  // 판정 자체는 순수 함수라 언제나 나온다. **빈칸에 첨삭을 띄우지 않는 것은 화면의 일**이고,
  // 그쪽은 notebook.js 의 gradeLine() 이 지킨다 — 여기서는 함수가 터지지 않는지만 본다.
  for (const q of QUESTIONS) {
    const r = gradeQuestion(q.id, '');
    assert.ok(['pass', 'more', 'unavailable'].includes(r.status));
  }
});

